def _resolve_type(preferred: str, current: str) -> str:
    """The base seed's initial policy-type assignment
    (policy_service.initial_policy_type_for_classification) is not guaranteed
    stable across a fresh reseed (no ORDER BY on the underlying pair query),
    so a hardcoded preferred type can coincidentally collide with whatever a
    SKU's real current type turns out to be this run - an illogical "switch
    to the same type" card. Falls back to the next type in POLICY_TYPES that
    isn't `current` when that happens, so the picked type always differs."""
    if preferred != current:
        return preferred
    for candidate in POLICY_TYPES:
        if candidate != current:
            return candidate
    raise RuntimeError("no alternative policy type available")  # unreachable: POLICY_TYPES has 5 entries


def _cost_split(total: float, holding_frac: float) -> tuple[float, float]:
    holding = round(total * holding_frac, 2)
    return holding, round(total - holding, 2)


async def _get_or_create(session: AsyncSession, sku_code: str, node_code: str) -> PolicyRecommendation:
    existing = (await session.scalars(
        select(PolicyRecommendation).where(PolicyRecommendation.sku_code == sku_code, PolicyRecommendation.node_code == node_code)
    )).first()
    if existing is None:
        existing = PolicyRecommendation(sku_code=sku_code, node_code=node_code)
        session.add(existing)
    return existing


async def seed_part_a(session: AsyncSession, as_of: date, computed_at: datetime, cost_pct: dict, vol_pct: dict):
    for row in PART_A:
        context = await recsvc.build_context(session, row["sku"], CHENNAI, as_of)
        if context is None:
            raise RuntimeError(f"No PolicySnapshot/cost/sku context for {row['sku']} at {CHENNAI} - seed real data first")

        current_composite = _composite(row["current"])
        suggested_composite = _composite(row["suggested"])
        assert 40 <= current_composite <= 79, f"{row['sku']} current composite {current_composite} out of 40-79 range"
        assert 80 <= suggested_composite <= 96, f"{row['sku']} suggested composite {suggested_composite} out of 80-96 range"
        assert suggested_composite > current_composite

        suggested_type = _resolve_type(row["suggested_type"], context["current_policy_type"])
        suggested_params = policy_params_for_type(suggested_type, context["computed"])
        if suggested_type in {"s_S", "s_Q", "R_s_S", "base_stock"}:
            suggested_params["safetyStock"] = context["computed"]["safety_stock"]

        reasoning = recsvc.build_reasoning(
            classification=context["classification"], volatility_ratio=context["volatility_ratio"],
            volatility_p33=vol_pct["p33"], volatility_p67=vol_pct["p67"],
            trend=context["trend"], cadence_days=context["cadence_days"], unit_cost=context["unit_cost"],
            median_cost=cost_pct["median"], p90_cost=cost_pct["p90"],
            current_policy_type=context["current_policy_type"], current_score=current_composite,
            governance_action="suggest_pending_approval",
            suggested_policy_type=suggested_type, suggested_score=suggested_composite,
        )

        current_holding, current_shortage = _cost_split(row["current_cost"], 0.84)
        suggested_holding, suggested_shortage = _cost_split(row["suggested_cost"], 0.93)

        rec = await _get_or_create(session, row["sku"], CHENNAI)
        rec.computed_at = computed_at
        rec.current_policy_type = context["current_policy_type"]
        rec.current_params = context["current_params"]
        rec.reasoning = reasoning
        rec.governance_action = "suggest_pending_approval"
        cc = _component_dict(row["current"])
        rec.current_composite_score = round(current_composite, 2)
        rec.current_service_stability = round(cc["service_stability"], 2)
        rec.current_stockout_resilience = round(cc["stockout_resilience"], 2)
        rec.current_cost_stability = round(cc["cost_stability"], 2)
        rec.current_expiry_robustness = round(cc["expiry_robustness"], 2)
        rec.current_inventory_stability = round(cc["inventory_stability"], 2)
        rec.current_service_level_achieved = round(row["current_sl"], 4)
        rec.current_total_cost = row["current_cost"]
        rec.current_total_holding_cost = current_holding
        rec.current_total_shortage_cost = current_shortage

        sc = _component_dict(row["suggested"])
        rec.suggested_policy_type = suggested_type
        rec.suggested_params = suggested_params
        rec.suggested_composite_score = round(suggested_composite, 2)
        rec.suggested_service_stability = round(sc["service_stability"], 2)
        rec.suggested_stockout_resilience = round(sc["stockout_resilience"], 2)
        rec.suggested_cost_stability = round(sc["cost_stability"], 2)
        rec.suggested_expiry_robustness = round(sc["expiry_robustness"], 2)
        rec.suggested_inventory_stability = round(sc["inventory_stability"], 2)
        rec.suggested_service_level_achieved = round(row["suggested_sl"], 4)
        rec.suggested_total_cost = row["suggested_cost"]
        rec.suggested_total_holding_cost = suggested_holding
        rec.suggested_total_shortage_cost = suggested_shortage
        rec.is_demo_seed = True


async def seed_part_b(session: AsyncSession, as_of: date, computed_at: datetime, cost_pct: dict, vol_pct: dict):
    for row in PART_B:
        context = await recsvc.build_context(session, row["sku"], CHENNAI, as_of)
        if context is None:
            raise RuntimeError(f"No PolicySnapshot/cost/sku context for {row['sku']} at {CHENNAI} - seed real data first")

        old_composite = _composite(row["old"])
        new_composite = _composite(row["new"])
        assert old_composite < 40, f"{row['sku']} old composite {old_composite} not below 40"
        assert 80 <= new_composite <= 96, f"{row['sku']} new composite {new_composite} out of 80-96 range"
        assert new_composite > old_composite

        new_type = _resolve_type(row["new_type"], context["current_policy_type"])
        new_params = policy_params_for_type(new_type, context["computed"])
        if new_type in {"s_S", "s_Q", "R_s_S", "base_stock"}:
            new_params["safetyStock"] = context["computed"]["safety_stock"]

        reasoning = recsvc.build_reasoning(
            classification=context["classification"], volatility_ratio=context["volatility_ratio"],
            volatility_p33=vol_pct["p33"], volatility_p67=vol_pct["p67"],
            trend=context["trend"], cadence_days=context["cadence_days"], unit_cost=context["unit_cost"],
            median_cost=cost_pct["median"], p90_cost=cost_pct["p90"],
            current_policy_type=context["current_policy_type"], current_score=old_composite,
            governance_action="auto_changed",
            suggested_policy_type=new_type, suggested_score=new_composite,
        )

        old_holding, old_shortage = _cost_split(row["old_cost"], 0.80)
        new_holding, new_shortage = _cost_split(row["new_cost"], 0.94)

        changed_at = computed_at - timedelta(days=row["days_ago"])

        rec = await _get_or_create(session, row["sku"], CHENNAI)
        rec.computed_at = computed_at
        rec.current_policy_type = context["current_policy_type"]
        rec.current_params = context["current_params"]
        rec.reasoning = reasoning
        rec.governance_action = "auto_changed"
        oc = _component_dict(row["old"])
        rec.current_composite_score = round(old_composite, 2)
        rec.current_service_stability = round(oc["service_stability"], 2)
        rec.current_stockout_resilience = round(oc["stockout_resilience"], 2)
        rec.current_cost_stability = round(oc["cost_stability"], 2)
        rec.current_expiry_robustness = round(oc["expiry_robustness"], 2)
        rec.current_inventory_stability = round(oc["inventory_stability"], 2)
        rec.current_service_level_achieved = round(row["old_sl"], 4)
        rec.current_total_cost = row["old_cost"]
        rec.current_total_holding_cost = old_holding
        rec.current_total_shortage_cost = old_shortage

        nc = _component_dict(row["new"])
        rec.suggested_policy_type = new_type
        rec.suggested_params = new_params
        rec.suggested_composite_score = round(new_composite, 2)
        rec.suggested_service_stability = round(nc["service_stability"], 2)
        rec.suggested_stockout_resilience = round(nc["stockout_resilience"], 2)
        rec.suggested_cost_stability = round(nc["cost_stability"], 2)
        rec.suggested_expiry_robustness = round(nc["expiry_robustness"], 2)
        rec.suggested_inventory_stability = round(nc["inventory_stability"], 2)
        rec.suggested_service_level_achieved = round(row["new_sl"], 4)
        rec.suggested_total_cost = row["new_cost"]
        rec.suggested_total_holding_cost = new_holding
        rec.suggested_total_shortage_cost = new_shortage
        rec.is_demo_seed = True

        # Idempotent audit log: replace this SKU/node's prior demo audit row(s)
        # rather than accumulating duplicates on repeated seed runs.
        prior = (await session.scalars(
            select(PolicyChangeAuditLog).where(
                PolicyChangeAuditLog.sku_code == row["sku"], PolicyChangeAuditLog.node_code == CHENNAI,
                PolicyChangeAuditLog.is_demo_seed == True,  # noqa: E712
            )
        )).all()
        for p in prior:
            await session.delete(p)

        session.add(PolicyChangeAuditLog(
            id=uuid.uuid4(), sku_code=row["sku"], node_code=CHENNAI,
            old_policy_type=context["current_policy_type"], old_params=context["current_params"],
            new_policy_type=new_type, new_params=new_params,
            robustness_score_at_change=round(old_composite, 2),
            changed_at=changed_at, changed_by=robustness_service.SYSTEM_CHANGED_BY,
            is_demo_seed=True,
        ))


async def seed_demo_robustness_showcase(session: AsyncSession):
    today = date.today()
    computed_at = datetime.now().replace(microsecond=0)
    cost_pct = await recsvc.cost_percentiles(session)
    vol_pct = await recsvc.volatility_percentiles(session)

    await seed_part_a(session, today, computed_at, cost_pct, vol_pct)
    await seed_part_b(session, today, computed_at, cost_pct, vol_pct)
    await session.commit()


async def main():
    async with SessionLocal() as session:
        await seed_demo_robustness_showcase(session)


if __name__ == "__main__":
    import asyncio
    asyncio.run(main())
