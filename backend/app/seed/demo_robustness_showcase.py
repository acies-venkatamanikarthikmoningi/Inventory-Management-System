"""DEMO/SHOWCASE SEED - Policy Robustness cards for Chennai DC.

WHY this exists: as of this seed's authoring, every real, live-computed
Chennai DC SKU/node pair lands in a non-actionable governance tier
(`no_change_needed` or `no_better_alternative_found` - confirmed via
GET /policy/recommendations before writing this script), so the "Waiting for
Approval" and "Auto-Approved" filters have nothing to show for a Chennai
demo/presentation session. This script hand-authors a small, clearly-flagged
set of override rows for a handful of REAL Chennai SKUs so those filters have
representative cards to present - the SAME honesty discipline this project
already applies to simulated demand/lead-time history (Phase 3/4/5): clearly
documented as seeded/demo, isolated from the real computation pipeline, and
identifiable/removable at the DATA level via `is_demo_seed=True` on both
PolicyRecommendation and PolicyChangeAuditLog (see migration
0010_demo_seed_flag) - not just by convention or a code comment.

What is REAL vs DEMO in each row:
  - sku_code, node, current_policy_type/current_params (Part A) or
    old_policy_type/old_params (Part B): REAL - read from this SKU's actual
    latest PolicySnapshot via policy_recommendation_service.build_context,
    unchanged.
  - suggested_policy_type/suggested_params (Part A) or new_policy_type/
    new_params (Part B): the TYPE is a demo choice (picked for variety across
    all 5 policy types); the concrete PARAMS are computed by the real
    `policy_service.policy_params_for_type()` formula against this SKU's real
    inputs - so they are structurally/numerically the same kind of number the
    real engine would have produced for that candidate type, just not
    selected as the actual highest-scorer.
  - All Robustness Score components/composites, service levels, and cost
    breakdowns: DEMO, hand-authored to land in the ranges the showcase needs
    (current 40-79 / suggested 80-96 for Part A, old <40 / new 80-96 for Part
    B) - and INTERNALLY CONSISTENT: each composite is computed from its own
    component scores via the exact real weighting formula (see `_composite`
    below, mirroring robustness_service.compute_robustness_score's weights),
    so a card's header score always matches the sum of its own displayed
    components, and a suggested/new score is always higher than the
    current/old one it replaces (never the "suggested scores lower" bug this
    project fixed for real data).
  - reasoning text: generated by the REAL
    policy_recommendation_service.build_reasoning() using this SKU's real
    classification/volatility/cost-percentile context, just narrating the
    DEMO scores - so it reads exactly like a real card's reasoning.

Isolation from the real pipeline: refresh_recommendations() skips any
SKU/node pair whose existing PolicyRecommendation row already has
is_demo_seed=True (see policy_recommendation_service.py) - a real network-wide
re-evaluation can never overwrite these rows. This script is also idempotent
(safe to re-run any time, e.g. after a real recalculation, to restore the
showcase rows if they were ever removed) - it upserts by (sku_code,
node_code) and replaces its own prior demo audit-log rows rather than
accumulating duplicates.

Run once: `python -m app.seed.demo_robustness_showcase` (or via
`docker compose exec api python -m app.seed.demo_robustness_showcase`).

To remove this showcase later: delete WHERE is_demo_seed = true from both
policy_recommendations and policy_change_audit_log, then re-run
POST /policy/recommendations/refresh so those SKU/node pairs get a real
evaluation again.
"""
