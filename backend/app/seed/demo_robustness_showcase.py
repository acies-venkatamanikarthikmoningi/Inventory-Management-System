# component order matches robustness_service.compute_robustness_score's
# weights exactly: 0.30 service_stability, 0.25 stockout_resilience,
# 0.20 cost_stability, 0.15 expiry_robustness, 0.10 inventory_stability
_WEIGHTS = (0.30, 0.25, 0.20, 0.15, 0.10)


def _composite(components: tuple[float, float, float, float, float]) -> float:
    return sum(w * c for w, c in zip(_WEIGHTS, components))


def _component_dict(components: tuple[float, float, float, float, float]) -> dict:
    keys = ("service_stability", "stockout_resilience", "cost_stability", "expiry_robustness", "inventory_stability")
    return dict(zip(keys, components))


